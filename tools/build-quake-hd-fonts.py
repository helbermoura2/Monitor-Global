"""Offline site typography atlases at native card sizes; SIL OFL (assets/summary-fonts)."""
import base64,io,json
from pathlib import Path
from PIL import Image,ImageDraw,ImageFont
ROOT=Path(__file__).resolve().parents[1]
CHARS=''.join(dict.fromkeys(''.join(chr(i) for i in range(32,127))+'ÁÀÂÃÄÅÉÈÊËÍÌÎÏÓÒÔÕÖÚÙÛÜÇÑáàâãäåéèêëíìîïóòôõöúùûüçñ·–—°ıİğĞşŞčČ'))
def atlas(size,weight,brand=False):
 font=ImageFont.truetype(str(ROOT/'assets/summary-fonts'/('Rajdhani-Bold.ttf' if brand else 'JetBrainsMono.ttf')),size)
 if not brand:font.set_variation_by_axes([weight])
 boxes={c:font.getbbox(c,anchor='ls') for c in CHARS};top=min(b[1] for b in boxes.values());bottom=max(b[3] for b in boxes.values())
 widths={c:max(2,b[2]-b[0]+2) for c,b in boxes.items()}
 image=Image.new('RGBA',(sum(widths.values()),bottom-top+2));draw=ImageDraw.Draw(image);glyphs={};x=0
 for c in CHARS:
  left=boxes[c][0];draw.text((x+1-left,1-top),c,font=font,fill='white',anchor='ls');glyphs[c]=[x,widths[c],round(font.getlength(c),3),1-left];x+=widths[c]
 png=io.BytesIO();image.save(png,format='PNG',optimize=True)
 return {'size':size,'cellH':image.height,'glyphs':glyphs,'b64':base64.b64encode(png.getvalue()).decode()}
fonts={str(size)+('-bold' if bold else '-regular'):atlas(size,800 if bold else 600) for size in [20,40,96] for bold in [False,True]}
fonts['40-brand']=atlas(40,700,True)
path=ROOT/'quake-hd-fonts.mjs';path.write_text('// Generated by tools/build-quake-hd-fonts.py. JetBrains Mono / Rajdhani, SIL OFL; licenses in assets/summary-fonts/OFL-*.txt.\nexport const QUAKE_HD_FONTS='+json.dumps(fonts,ensure_ascii=False,separators=(',',':'))+';\n')
print('Generated HD font atlases:',path.stat().st_size,'bytes')
