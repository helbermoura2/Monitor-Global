"""Prepare the approved Tual raster for dynamic earthquake composition."""

import base64
import hashlib
from io import BytesIO
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
source = ROOT / "assets/telegram/m6/imperial-bronze-preview-2026-11-16-m6-6.png"
assert hashlib.sha256(source.read_bytes()).hexdigest() == (
    "ed3cf9da86aa041673d98a40172649b498e879137da9a2b8a40810f6fe699a75"
)

art = Image.open(source).convert("RGB")
# Coordinates use half the resolution of the approved raster.
def region(box):
    return tuple(2 * value for value in box)

def texture(target, sample, flip=False):
    x, y, right, bottom = region(target)
    tile = art.crop(region(sample))
    if flip:
        tile = ImageOps.mirror(tile)
    art.paste(tile.resize((right - x, bottom - y), Image.Resampling.LANCZOS), (x, y))

original = art.copy()
# Fill the geographic panel with overlapping sections of ocean from the reference.
map_box = (8, 156, 504, 535)
texture(map_box, (391, 245, 464, 480))
tile_width = 136
for index, left in enumerate(range(8, 504, 96)):
    sample_y = 245 + (index * 23) % 70
    tile = original.crop(region((391, sample_y, 464, sample_y + 208)))
    if index % 2:
        tile = ImageOps.mirror(tile)
    if index % 3 == 2:
        tile = ImageOps.flip(tile)
    tile = tile.resize((tile_width * 2, (535 - 156) * 2), Image.Resampling.LANCZOS)
    width = min(tile.width, (504 - left) * 2)
    mask = Image.new("L", (width, 1))
    mask.putdata([min(255, round(x / 80 * 255)) if index else 255 for x in range(width)])
    art.paste(tile.crop((0, 0, width, tile.height)), (left * 2, 312), mask.resize((width, tile.height)))

for box in [(20, 169, 160, 237), (222, 467, 291, 534)]:
    x, y, right, bottom = region(box)
    piece = original.crop((x, y, right, bottom))
    mask = Image.new("L", piece.size)
    mask.putdata([min(255, 32 * min(px, py, piece.width - 1 - px, piece.height - 1 - py))
                  for py in range(piece.height) for px in range(piece.width)])
    art.paste(piece, (x, y), mask)
# Replace event-specific lettering while keeping the engraved panel edges and labels.
panel_texture = (70, 654, 188, 666)
for box in [(34, 118, 479, 146), (31, 178, 151, 228),
            (56, 575, 169, 613), (210, 577, 299, 609),
            (349, 576, 454, 610), (55, 626, 209, 652),
            (226, 622, 460, 644)]:
    texture(box, panel_texture)

out = BytesIO()
art.quantize(colors=256, method=Image.Quantize.FASTOCTREE).save(out, format="PNG", optimize=True)
encoded = base64.b64encode(out.getvalue()).decode()
(ROOT / "worker/telegram-tual-art.mjs").write_text(
    "// Generated by tools/build-tual-alert-art.py from the approved Tual PNG.\n"
    f"export const TUAL_ART_BASE64 = '{encoded}';\n"
)

