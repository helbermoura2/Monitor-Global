"""Deterministic small TV references, from the project's public-domain Natural Earth data."""
import json, pathlib, math
root=pathlib.Path(__file__).resolve().parents[1]
def simplify(points, eps=.035):
 if len(points)<3:return points
 a,b=points[0],points[-1]; dx,dy=b[0]-a[0],b[1]-a[1]; den=dx*dx+dy*dy
 best,idx=0,0
 for i,p in enumerate(points[1:-1],1):
  t=max(0,min(1,((p[0]-a[0])*dx+(p[1]-a[1])*dy)/den)) if den else 0
  d=(p[0]-a[0]-t*dx)**2+(p[1]-a[1]-t*dy)**2
  if d>best:best,idx=d,i
 if best>eps*eps:return simplify(points[:idx+1],eps)[:-1]+simplify(points[idx:],eps)
 return [a,b]
def coords(value):
 if not value:return []
 if isinstance(value[0][0],(int,float)):
  pts=[[round(p[0],3),round(p[1],3)] for p in simplify(value)]
  return pts if len(pts)>=2 else []
 return [coords(v) for v in value]
def geometry(g):return {'type':g['type'],'coordinates':coords(g['coordinates'])}
land=json.loads((root/'assets/seismic/ne-50m-land.geojson').read_text())
rings=[]
for f in land['features']:
 g=geometry(f['geometry']); rings.extend(g['coordinates'] if g['type']=='Polygon' else [r for polygon in g['coordinates'] for r in polygon])
(root/'android-tv/app/src/main/assets/maps/land.json').write_text(json.dumps(rings,separators=(',',':'))+'\n')
coasts=json.loads((root/'assets/tsunami/ne-50m-coastal-regions.geojson').read_text())
features=[]
for f in coasts['features']:
 if f.get('coastlineGeometry'):features.append({'type':'Feature','properties':f['properties'],'geometry':{'type':'MultiLineString','coordinates':[]},'coastlineGeometry':geometry(f['coastlineGeometry'])})
(root/'worker/tv-coastal-references.mjs').write_text('// Generated by tools/build-tv-map-assets.py; Natural Earth, public domain. Geographic references, never inundation.\nexport default '+json.dumps({'type':'FeatureCollection','features':features},separators=(',',':'))+';\n')
print('TV land / coast bytes:',(root/'android-tv/app/src/main/assets/maps/land.json').stat().st_size,(root/'worker/tv-coastal-references.mjs').stat().st_size)
